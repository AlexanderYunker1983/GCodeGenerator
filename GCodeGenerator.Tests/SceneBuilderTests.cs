            Assert.AreEqual(9, seg.InterpolatedPoints.Count);
            // midpoint at 45° from center: (Y = 10·cos45, Z = 10·sin45)
            AssertPoint(seg.InterpolatedPoints[4], 0, 10 * Math.Sqrt(2) / 2, 10 * Math.Sqrt(2) / 2, "arc midpoint");
        }

        [TestMethod]
        public void Arc_WithZMove_InterpolatesThirdAxis()
        {
            var program = new GCodeProgram();

        [TestMethod]
        public void Arc_IJK_XYPlane_QuarterArc()
        {
            var program = new GCodeProgram();
            // (10,0) → (0,10) around center (0,0), CCW: I = -10, J = 0
            program.Blocks.Add(Block(GCodeWord.G(0), W('X', 10), W('Y', 0)));
            program.Blocks.Add(Block(GCodeWord.G(3), W('X', 0), W('Y', 10), W('I', -10), W('J', 0), W('F', 100)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[1];
            Assert.AreEqual(MoveType.ArcCCW, seg.MoveType);
            AssertPoint(seg.ArcCenter.Value, 0, 0, 0, "center");
            Assert.IsTrue(Math.Abs(seg.ArcRadius - 10) < Tol, $"radius: {seg.ArcRadius}");
            Assert.IsNotNull(seg.InterpolatedPoints);

            // quarter circle → totalAngle = π/2 → segments = max((int)(8), 4) = 8 → 9 points
            Assert.AreEqual(9, seg.InterpolatedPoints.Count);
            AssertPoint(seg.InterpolatedPoints[0], 10, 0, 0, "arc start");
            AssertPoint(seg.InterpolatedPoints[seg.InterpolatedPoints.Count - 1], 0, 10, 0, "arc end");
            // midpoint at 45°: (10·cos45, 10·sin45)
            AssertPoint(seg.InterpolatedPoints[4], 10 * Math.Sqrt(2) / 2, 10 * Math.Sqrt(2) / 2, 0, "arc midpoint");
        }

        [TestMethod]
        public void Arc_R_Positive_Clockwise()
        {
            var program = new GCodeProgram();
            // (0,0) → (10,0), R=10, G2: center (5, -√75)
            program.Blocks.Add(Block(GCodeWord.G(2), W('X', 10), W('Y', 0), W('R', 10), W('F', 100)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[0];
            Assert.AreEqual(MoveType.ArcCW, seg.MoveType);
            Assert.IsTrue(Math.Abs(seg.ArcRadius - 10) < Tol, $"radius: {seg.ArcRadius}");
            Assert.IsNotNull(seg.InterpolatedPoints);

            // 60° arc → segments = max((int)(1.0472/0.19635), 4) = 5 → 6 points
            Assert.AreEqual(6, seg.InterpolatedPoints.Count);
            AssertPoint(seg.InterpolatedPoints[0], 0, 0, 0, "arc start");
            AssertPoint(seg.InterpolatedPoints[5], 10, 0, 0, "arc end");
            // point 3 of 6 (t = 0.6): angle = 120° − 0.6·60° = 84° = 7π/15
            // from center (5, −√75): (5 + 10·cos84°, −√75 + 10·sin84°)
            var angle = 7.0 * Math.PI / 15.0;
            AssertPoint(seg.InterpolatedPoints[3],
                5 + 10 * Math.Cos(angle), -Math.Sqrt(75) + 10 * Math.Sin(angle), 0, "arc point 3");
        }

        [TestMethod]
        public void Arc_R_Negative_TakesTheLongWay()
        {
            var program = new GCodeProgram();
            // (0,0) → (10,0), R=-10, G2: center (5, +√75), 300° arc
            program.Blocks.Add(Block(GCodeWord.G(2), W('X', 10), W('Y', 0), W('R', -10), W('F', 100)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[0];
            Assert.AreEqual(MoveType.ArcCW, seg.MoveType);
            Assert.IsNotNull(seg.InterpolatedPoints);

            // 300° arc → segments = max((int)(26.67), 4) = 26 → 27 points
            Assert.AreEqual(27, seg.InterpolatedPoints.Count);
            // midpoint of the 300° sweep: angle -270° ≡ 90° from center (5, +8.6603)
            var mid = seg.InterpolatedPoints[13];
            AssertPoint(mid, 5, Math.Sqrt(75) + 10, 0, "arc midpoint");
        }

        [TestMethod]
        public void Arc_R_TooSmall_FallsBackToLinearPoints()
        {
            var program = new GCodeProgram();
            // chord = 10, |R| = 4 < 5 → linear fallback [start, end]
            program.Blocks.Add(Block(GCodeWord.G(2), W('X', 10), W('Y', 0), W('R', 4), W('F', 100)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[0];
            Assert.AreEqual(2, seg.InterpolatedPoints.Count);
            AssertPoint(seg.InterpolatedPoints[0], 0, 0, 0, "start");
            AssertPoint(seg.InterpolatedPoints[1], 10, 0, 0, "end");
        }

        [TestMethod]
        public void Arc_SmallAngle_MinimumFourSegments()
        {
            var program = new GCodeProgram();
            // 30° arc around (0,0): (10,0) → (10·cos30, 10·sin30)
            program.Blocks.Add(Block(GCodeWord.G(0), W('X', 10), W('Y', 0)));
            program.Blocks.Add(Block(GCodeWord.G(3), W('X', 10 * Math.Cos(Math.PI / 6)), W('Y', 10 * Math.Sin(Math.PI / 6)), W('I', -10), W('J', 0)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[1];
            // 30° → (int)(16/6) = 2 → max(2, 4) = 4 → 5 points
            Assert.AreEqual(5, seg.InterpolatedPoints.Count);
        }

        [TestMethod]
        public void Arc_XZPlane_FullCircle_32Segments()
        {
            var program = new GCodeProgram();
            // G18 (XZ): (X=10, Z=0) → (X=10, Z=0) with Y 0→5: full circle in XZ,
            // Y interpolated linearly. Center (0, 0, 0): I = -10, K = 0.
            program.Blocks.Add(Block(GCodeWord.G(18)));
            program.Blocks.Add(Block(GCodeWord.G(0), W('X', 10), W('Z', 0)));
            program.Blocks.Add(Block(GCodeWord.G(2), W('X', 10), W('Z', 0), W('Y', 5), W('I', -10), W('K', 0)));

            var scene = SceneBuilder.Build(program);
            var seg = scene.Segments[1]; // [0] — rapid, G18-блок сегмента не создаёт
            Assert.AreEqual(MoveType.ArcCW, seg.MoveType);
            AssertPoint(seg.ArcCenter.Value, 0, 0, 0, "center");

            // full circle → 32 segments → 33 points
            Assert.AreEqual(33, seg.InterpolatedPoints.Count);
            AssertPoint(seg.InterpolatedPoints[0], 10, 0, 0, "arc start");
            AssertPoint(seg.InterpolatedPoints[32], 10, 5, 0, "arc end (Y moved)");
            // point at a quarter of the CW sweep: angle -90° → (X=0, Z=-10), Y = 1.25
            AssertPoint(seg.InterpolatedPoints[8], 0, 1.25, -10, "arc quarter point");
        }

        [TestMethod]
        public void Arc_YZPlane_QuarterArc()

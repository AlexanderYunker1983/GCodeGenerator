using System;
using GCodeGenerator.Models;
using GCodeGenerator.Trajectory;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace GCodeGenerator.Tests
{
    /// <summary>
    /// Unit tests for <see cref="SceneBuilder"/> (plan item 6.4): segments
    /// from structured GCodeProgram blocks — modal G state, arc planes,
    /// I/J/K and R arcs, M30/M2, G92, arc interpolation, bounds.
    /// </summary>
    [TestClass]
    public class SceneBuilderTests
    {
        private const double Tol = 1e-9;

        private static GCodeBlock Block(params GCodeWord[] words) => new GCodeBlock(words);

        private static GCodeWord W(char letter, double number, int decimals = 3) => new GCodeWord(letter, number, decimals);

        private static Vec3 Pt(double x, double y, double z) => new Vec3(x, y, z);

        private static void AssertPoint(Vec3 actual, double x, double y, double z, string what)
        {
            Assert.IsTrue(Math.Abs(actual.X - x) < Tol && Math.Abs(actual.Y - y) < Tol && Math.Abs(actual.Z - z) < Tol,
                $"{what}: expected ({x}, {y}, {z}), got {actual}");
        }

        // ------------------------------------------------------------------
        // Basics
        // ------------------------------------------------------------------

        [TestMethod]
        public void EmptyProgram_ProducesEmptyScene()
        {
            var scene = SceneBuilder.Build(new GCodeProgram());
            Assert.IsTrue(scene.IsEmpty);
            Assert.IsNull(scene.Bounds);
        }

        [TestMethod]
        public void NullProgram_ProducesEmptyScene()
        {
            var scene = SceneBuilder.Build(null);
            Assert.IsTrue(scene.IsEmpty);
        }

        [TestMethod]
        public void RapidAndLinear_Segments()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5)));
            program.Blocks.Add(Block(GCodeWord.G(1), W('X', 10), W('Y', 20)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(2, scene.Segments.Count);

            var s0 = scene.Segments[0];
            Assert.AreEqual(MoveType.Rapid, s0.MoveType);
            AssertPoint(s0.Start, 0, 0, 0, "s0.Start");
            AssertPoint(s0.End, 0, 0, 5, "s0.End");

            var s1 = scene.Segments[1];
            Assert.AreEqual(MoveType.Linear, s1.MoveType);
            AssertPoint(s1.Start, 0, 0, 5, "s1.Start");
            AssertPoint(s1.End, 10, 20, 5, "s1.End");
        }

        [TestMethod]
        public void ModalMoveType_PersistsUntilChanged()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(1), W('X', 1)));
            program.Blocks.Add(Block(W('X', 2))); // no G word → stays Linear
            program.Blocks.Add(Block(GCodeWord.G(0), W('X', 3)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(3, scene.Segments.Count);
            Assert.AreEqual(MoveType.Linear, scene.Segments[0].MoveType);
            Assert.AreEqual(MoveType.Linear, scene.Segments[1].MoveType);
            Assert.AreEqual(MoveType.Rapid, scene.Segments[2].MoveType);
        }

        [TestMethod]
        public void LastMotionGInLine_Wins()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(1), GCodeWord.G(0), W('X', 1)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(MoveType.Rapid, scene.Segments[0].MoveType);
        }

        [TestMethod]
        public void SamePosition_NoSegment()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5)));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5))); // no position change

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(1, scene.Segments.Count);
        }

        [TestMethod]
        public void CommentAndHeaderBlocks_AreSkipped()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(new GCodeBlock(null, "Profile: test"));
            program.Blocks.Add(Block(GCodeWord.Raw("(Generated by GCodeGenerator)")));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(1, scene.Segments.Count);
        }

        [TestMethod]
        public void M30_Line_IsSkipped()
        {
            // Как и в старом текстовом парсере, SceneBuilder пропускает только
            // саму строку M30 (в генерируемых программах M30 всегда последняя);
            // блоки после неё обрабатываются.
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5)));
            program.Blocks.Add(Block(GCodeWord.Raw("M30")));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 10)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(2, scene.Segments.Count);
            AssertPoint(scene.Segments[1].End, 0, 0, 10, "move after M30 line");
        }

        [TestMethod]
        public void M2_Line_IsSkipped()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 5)));
            program.Blocks.Add(Block(GCodeWord.M(2)));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 10)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(2, scene.Segments.Count);
            AssertPoint(scene.Segments[1].End, 0, 0, 10, "move after M2 line");
        }

        [TestMethod]
        public void G92_UpdatesPositionWithoutSegment()
        {
            var program = new GCodeProgram();
            program.Blocks.Add(Block(GCodeWord.Raw("G92"), W('X', 10, -1), W('Z', 5, -1)));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Z', 10)));

            var scene = SceneBuilder.Build(program);
            Assert.AreEqual(1, scene.Segments.Count);
            // G92 updated the tracked position: the move starts from (10, 0, 5)
            AssertPoint(scene.Segments[0].Start, 10, 0, 5, "start after G92");
            AssertPoint(scene.Segments[0].End, 10, 0, 10, "end");
        }


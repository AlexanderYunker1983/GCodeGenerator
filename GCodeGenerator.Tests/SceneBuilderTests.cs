            var program = new GCodeProgram();
            // G19 (YZ): (Y=10, Z=0) → (Y=0, Z=10) around center (0,0,0): J = -10, K = 0
            program.Blocks.Add(Block(GCodeWord.G(19)));
            program.Blocks.Add(Block(GCodeWord.G(0), W('Y', 10)));
            program.Blocks.Add(Block(GCodeWord.G(3), W('Y', 0), W('Z', 10), W('J', -10), W('K', 0)));

            var scene = SceneBuilder.Build(program);

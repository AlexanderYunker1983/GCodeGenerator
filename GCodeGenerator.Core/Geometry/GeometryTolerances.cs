#nullable enable
namespace GCodeGenerator.Geometry
{
    /// <summary>
    /// Геометрические допуски продукта в одном месте.
    ///
    /// До этого одни и те же сравнения выполнялись с числами, записанными
    /// прямо в коде: 0.001 в импорте DXF и в проверке замкнутости контура,
    /// 1e-6 в генераторах траектории, 1e-9 в вырожденных случаях. Значения
    /// совпадали не всегда, а связь между ними нигде не была зафиксирована:
    /// точки, «совпадающие» для импортёра, для генератора были разными.
    ///
    /// Значения сохранены такими, какими были в коде, — этот контракт
    /// именует уже сложившиеся допуски, а не меняет поведение генератора.
    ///
    /// Здесь только допуски сравнения геометрии. Пороги, описывающие
    /// физические величины обработки (минимальный шаг, минимальный припуск,
    /// минимальный размер контура относительно фрезы), остаются рядом
    /// с соответствующим расчётом: у них своя единица измерения и свой смысл.
    /// </summary>
    public static class GeometryTolerances
    {
        /// <summary>
        /// Совпадение точек модели, мм. Допуск исходных данных: точность
        /// координат в DXF и в файле проекта. С ним соединяются отрезки
        /// в контур и проверяется замкнутость контура операции.
        /// </summary>
        public const double PointCoincidence = 1e-3;

        /// <summary>
        /// Совпадение соседних вершин траектории, мм. Допуск вычислений:
        /// им отбрасываются повторяющиеся точки контура и определяется,
        /// замкнут ли уже построенный путь.
        /// </summary>
        public const double Vertex = 1e-6;

        /// <summary>
        /// Допуск принадлежности точки контуру, мм. Точка на самой границе
        /// (в пределах этого допуска) считается лежащей внутри, иначе
        /// траектория обрывалась бы на собственной границе из-за округления.
        /// </summary>
        public const double Containment = 1e-6;

        /// <summary>
        /// Порог вырожденности. Применяется к величинам, которые обращаются
        /// в ноль при вырождении задачи: длина отрезка, определитель системы
        /// при поиске пересечения, площадь треугольника в тесте поворота.
        /// Значение меньше остальных допусков намеренно: здесь отделяется
        /// «математический ноль», а не близкие друг к другу точки.
        /// </summary>
        public const double Degenerate = 1e-9;

        /// <summary>
        /// Изменение положения инструмента, мм. Перемещение меньше этого
        /// не создаёт сегмента траектории при разборе программы для превью.
        /// </summary>
        public const double Position = 1e-4;

        /// <summary>
        /// Минимальный ненулевой размер контура, мм. Подставляется вместо
        /// нулевого или отрицательного радиуса (полуразмера) после вычитания
        /// радиуса инструмента: нулевой контур обрушил бы построение точек,
        /// а такой вырожденный контур отсекается проверкой размера.
        /// </summary>
        public const double MinimumContourExtent = 1e-3;
    }
}

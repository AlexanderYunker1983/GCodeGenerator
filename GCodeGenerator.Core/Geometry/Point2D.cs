#nullable enable
using System.Collections.Generic;

namespace GCodeGenerator.Models
{
    /// <summary>
    /// Точка на плоскости, миллиметры.
    ///
    /// Раньше тип назывался по формату, из которого пришёл, — «точка DXF», —
    /// и при этом служил основным примитивом всей геометрии продукта: им
    /// оперировали смещение контура, расчёт площади, поиск пересечений,
    /// проверка замкнутости. Имя обещало связь с чертежом там, где её нет.
    ///
    /// Тип остаётся в пространстве имён моделей: он часть формата файла
    /// проекта, где точки контура хранятся именно так.
    /// </summary>
    public class Point2D
    {
        public double X { get; set; }

        public double Y { get; set; }
    }

    /// <summary>
    /// Ломаная на плоскости: последовательность точек. Контур из чертежа,
    /// набор отрезков профиля, замкнутая граница кармана — всё это она.
    /// </summary>
    public class Polyline2D
    {
        public List<Point2D> Points { get; set; } = new List<Point2D>();
    }
}

#nullable enable
using GCodeGenerator.Toolpath;

namespace GCodeGenerator.GCodeGenerators.Strategies
{
    /// <summary>
    /// Повторный вход в слой кармана: подъём над заготовкой, перенос в новую
    /// точку и врезание на рабочую глубину.
    ///
    /// Стратегия выборки возвращается к этому в каждом месте, где очередной
    /// проход начинается не там, где закончился предыдущий: отдельный рез
    /// параллельной линии, участок луча или контура за островом, разорванный
    /// островом виток спирали, чистовой проход по стенке. Точка входа при этом
    /// лежит в невыбранном материале — на первом слое там полная высота
    /// прохода.
    ///
    /// Прежде все эти места опускали инструмент одним быстрым ходом сразу на
    /// рабочую глубину: <c>G0 Z&lt;дно слоя&gt;</c> означает удар торцом фрезы
    /// по материалу на холостой подаче. Правило, по которому это делается
    /// верно, в продукте уже было — вертикальный подвод
    /// (<see cref="PocketEntryGenerator"/>) быстрым ходом доходит до верха
    /// слоя и дальше идёт рабочей подачей по Z, и точно так же поступает
    /// переход между контурами профиля. Здесь оно записано один раз для всех
    /// стратегий.
    ///
    /// Вход остаётся вертикальным даже тогда, когда операция задаёт винтовой:
    /// винтовой подвод требует, чтобы в точке входа помещалась окружность
    /// заданного диаметра, а участок сегмента или узкая область у стенки
    /// такого места не дают. Винтовым остаётся подвод к слою, который делает
    /// <see cref="PocketEntryGenerator"/> в заведомо пригодной точке.
    /// </summary>
    public static class PocketLayerEntry
    {
        /// <summary>
        /// Переводит инструмент в точку (<paramref name="x"/>,
        /// <paramref name="y"/>) на рабочую глубину слоя через безопасную
        /// высоту. По завершении инструмент стоит в этой точке на
        /// <see cref="PocketLayerContext.WorkingZ"/> — там, где очередной
        /// проход начинает резать.
        /// </summary>
        /// <param name="layer">Слой кармана: высоты, подачи и операция.</param>
        /// <param name="builder">Построитель траектории.</param>
        /// <param name="x">X точки входа.</param>
        /// <param name="y">Y точки входа.</param>
        public static void Enter(PocketLayerContext layer, ToolPathBuilder builder, double x, double y)
        {
            var op = layer.Operation;

            builder.RapidTo(z: op.SafeZHeight, feed: op.FeedZRapid);
            builder.RapidTo(x: x, y: y, feed: op.FeedXYRapid);
            builder.RapidTo(z: layer.LayerTopZ, feed: op.FeedZRapid);
            builder.LinearTo(z: layer.WorkingZ, feed: op.FeedZWork);
        }
    }
}
